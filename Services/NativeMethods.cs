    public static string ReadUnicodeString(UNICODE_STRING str)
    {
        if (str.Length == 0 || str.Buffer == IntPtr.Zero)
        {
            return string.Empty;
        }

        int charCount = str.Length / 2;
        return Marshal.PtrToStringUni(str.Buffer, charCount) ?? string.Empty;
    }

    public static int ConvertNetworkPort(uint rawPort)
    {
        ushort port = (ushort)rawPort;
        return ((port & 0xFF) << 8) | ((port >> 8) & 0xFF);
    }

    public static string ReadNullTerminatedUnicode(IntPtr ptr)
    {
        if (ptr == IntPtr.Zero)
        {
            return string.Empty;
        }

        return Marshal.PtrToStringUni(ptr) ?? string.Empty;
    }

